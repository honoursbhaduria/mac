import { Download } from "lucide-react";
import { AnalysisGate } from "../components/feedback/AnalysisGate";
import { StatusStrip } from "../components/feedback/StatusStrip";
import { Bay } from "../components/layout/Bay";
import { PageOpening } from "../components/layout/PageOpening";
import { RecordsTable } from "../components/tables/RecordsTable";
import { usePageAnalysis } from "../hooks/usePageAnalysis";
import { exportCsvUrl } from "../services/export";

export function RecordsPage() {
  const { filters, query } = usePageAnalysis();
  return (
    <>
      <PageOpening
        title="Detailed records"
        busy={query.isFetching}
        lede="Every hourly delivery interval in the selected window, including intervals with missing data. Select a delivery time to inspect its forecast vintages."
      />
      <StatusStrip data={query.data} isFetching={query.isFetching} isError={query.isError} />
      <Bay
        num="02"
        id="records"
        title="Interval table"
        aside={
          <a className="btn-primary" href={exportCsvUrl(filters)} download data-testid="csv-export">
            <Download size={15} aria-hidden="true" />
            Export CSV
          </a>
        }
      >
        <p className="meta mb-3">
          The CSV is generated by the server with the same filters and matching rules as this table, and
          includes timestamps, status and data-quality flags for every interval.
        </p>
        <AnalysisGate query={query} skeletonHeight={400}>
          {(data, refreshing) => (
            <div className={refreshing ? "opacity-60" : undefined}>
              <RecordsTable rows={data.intervals} />
            </div>
          )}
        </AnalysisGate>
      </Bay>
    </>
  );
}
